export const INDONESIAN_BIG_WISHES = (name: string, relationship: string, interests: string[] = []) => {
    const wishes = [
        { emoji: "🚀", wish: `Semoga reputasi dan langkah ${name} melesat tinggi menembus bintang tahun ini!` },
        { emoji: "💎", wish: `Kamu adalah permata berharga yang selalu bersinar, ${name}. Tetaplah memesona!` }
    ];
    if (relationship === 'partner') {
        wishes.push(
            { emoji: "❤️", wish: `Setiap detak jantungku adalah doa tulus untuk kebahagiaanmu, ${name}.` },
            { emoji: "💍", wish: `Menuju tahun-tahun indah berikutnya bersama, membuat dunia iri pada indahnya cinta kita.` }
        );
    } else if (relationship === 'friend') {
        wishes.push(
            { emoji: "🔥", wish: `Tetaplah menjadi legenda, berjiwa bebas, dan terus menginspirasi banyak orang, ${name}!` },
            { emoji: "🍻", wish: `Untuk tawa malam yang tak terlupakan dan persahabatan yang abadi selamanya.` }
        );
    }
    if (interests.some(i => i.toLowerCase().includes('car'))) {
        wishes.push({ emoji: "🏎️", wish: `Semoga hidupmu melesat kencang dari 0 ke 100 dalam kebahagiaan murni tahun ini!` });
    }
    if (interests.some(i => i.toLowerCase().includes('coding'))) {
        wishes.push({ emoji: "💻", wish: `Semoga hidupmu bebas dari bug dan dipenuhi fitur kebahagiaan tanpa batas, ${name}!` });
    }
    return wishes;
};

